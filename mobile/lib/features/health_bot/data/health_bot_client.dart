class HealthBotClientException implements Exception {
  final String message;
  HealthBotClientException(this.message);

  @override
  String toString() => message;
}

/// The request took longer than the client's budget (FR8 response-time
/// target). The controller answers locally instead.
class HealthBotTimeoutException extends HealthBotClientException {
  HealthBotTimeoutException(super.message);
}

/// The backend couldn't be reached at all (no connection, refused, DNS).
/// The controller answers locally instead.
class HealthBotUnreachableException extends HealthBotClientException {
  HealthBotUnreachableException(super.message);
}

/// The user's sign-in couldn't be verified (missing/expired token, HTTP
/// 401/403). The only failure whose message is shown under the reply,
/// because the user can act on it by signing in again.
class HealthBotAuthException extends HealthBotClientException {
  HealthBotAuthException(super.message);
}

enum HealthBotAnswerType { matched, emergency, unmatched }

/// Where an answer's text came from, so curated, rule-based or offline
/// guidance is never presented as AI-generated.
enum HealthBotAnswerSource {
  /// Generated by Gemini on the backend.
  ai,

  /// Reviewed knowledge-base text from the backend (used when Gemini was
  /// too slow or unavailable).
  curated,

  /// Emergency referral or medication guard.
  safety,

  /// Produced on the device because the backend couldn't answer.
  offline,

  /// An older backend that doesn't report the source.
  unknown,
}

HealthBotAnswerSource parseHealthBotAnswerSource(Object? raw) => switch (raw) {
  'ai' => HealthBotAnswerSource.ai,
  'curated' => HealthBotAnswerSource.curated,
  'safety' => HealthBotAnswerSource.safety,
  _ => HealthBotAnswerSource.unknown,
};

/// Why the backend used curated text instead of a Gemini reply.
enum HealthBotFallbackReason { timeout, unavailable }

HealthBotFallbackReason? parseHealthBotFallbackReason(Object? raw) =>
    switch (raw) {
      'timeout' => HealthBotFallbackReason.timeout,
      'unavailable' => HealthBotFallbackReason.unavailable,
      _ => null,
    };

/// FR8: a trusted public-health page relevant to the answer's topic
/// (backend/app/healthbot/sources.py). A pointer for further reading, not
/// an endorsement of the generated wording.
class HealthBotSource {
  final String title;
  final String url;

  const HealthBotSource({required this.title, required this.url});

  Map<String, String> toMap() => {'title': title, 'url': url};

  static HealthBotSource? fromMap(Object? value) {
    if (value is! Map) return null;
    final title = value['title'];
    final url = value['url'];
    if (title is! String || url is! String) return null;
    if (!url.startsWith('https://')) return null;
    return HealthBotSource(title: title, url: url);
  }

  @override
  bool operator ==(Object other) =>
      other is HealthBotSource && other.title == title && other.url == url;

  @override
  int get hashCode => Object.hash(title, url);
}

class HealthBotAnswer {
  final HealthBotAnswerType type;
  final String responseText;
  final List<HealthBotSource> sources;

  /// True when the answer was produced on the device because the backend
  /// was unreachable or too slow (see LocalHealthBotFallback).
  final bool isLocalFallback;

  /// Backend-reported (or, for local fallbacks, device-assigned) origin of
  /// [responseText].
  final HealthBotAnswerSource source;

  /// Set when the backend replaced a Gemini reply with curated text.
  final HealthBotFallbackReason? fallbackReason;

  const HealthBotAnswer({
    required this.type,
    required this.responseText,
    this.sources = const [],
    this.isLocalFallback = false,
    this.source = HealthBotAnswerSource.unknown,
    this.fallbackReason,
  });
}

/// One earlier chat message sent with a question, so the backend can
/// understand follow-ups ("what about vaping?", "explain that simpler").
class HealthBotTurn {
  /// True for the user's message, false for a Health-Bot reply.
  final bool fromUser;
  final String text;

  const HealthBotTurn({required this.fromUser, required this.text});

  Map<String, String> toJson() => {
    'role': fromUser ? 'user' : 'assistant',
    'text': text,
  };

  @override
  bool operator ==(Object other) =>
      other is HealthBotTurn && other.fromUser == fromUser && other.text == text;

  @override
  int get hashCode => Object.hash(fromUser, text);
}

/// Minimal, non-identifying profile details for personalised replies: no
/// name, email, phone number or free text.
class HealthBotUserContext {
  /// ProductType name: vape, cigarettes, pouches or hookah.
  final String? product;

  /// Whole days since the quit date (or the last restart); negative when
  /// the quit date is still ahead.
  final int? daysSinceQuit;

  /// QuitStrategy name: coldTurkey, gradual or dateBased.
  final String? quitStrategy;

  const HealthBotUserContext({
    this.product,
    this.daysSinceQuit,
    this.quitStrategy,
  });

  bool get isEmpty =>
      product == null && daysSinceQuit == null && quitStrategy == null;

  Map<String, Object> toJson() => {
    'product': ?product,
    'days_since_quit': ?daysSinceQuit,
    'quit_strategy': ?quitStrategy,
  };
}

/// Talks to the FastAPI backend's POST /healthbot/query (FR8, Module 6
/// plan) for Gemini-generated Health-Bot replies.
abstract class HealthBotClient {
  /// [history] holds the most recent earlier messages (oldest first) and
  /// [userContext] the user's quit details; both are optional.
  Future<HealthBotAnswer> ask({
    required String query,
    List<HealthBotTurn> history = const [],
    HealthBotUserContext? userContext,
  });
}
